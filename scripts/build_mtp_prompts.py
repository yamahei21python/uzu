#!/usr/bin/env python3
"""Collect prompt-only training data for a DFlash draft.

The draft has to reproduce *our* model's continuations, so it is trained on text
generated by that model. What it needs from this script is only the prompts: a
mix that covers the domains the draft must accept well, weighted toward the
places where an uncensored fine-tune differs from the aligned base.

`research/eval_prompts_{ja,en}.jsonl` stays the holdout; every prompt produced
here is checked against it so the evaluation never leaks into training.

Usage:
    python scripts/build_mtp_prompts.py --out data/mtp_prompts --dry-run
    python scripts/build_mtp_prompts.py --out data/mtp_prompts --per-source 2000
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import re
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGE_DELAY_S = 1.5
ROWS_API = "https://datasets-server.huggingface.co/rows"
SPLITS_API = "https://datasets-server.huggingface.co/splits"

# Only licences that allow redistribution of derived data are accepted here.
SOURCES = (
    {"dataset": "Open-Orca/OpenOrca", "field": "question", "lang": "en", "category": "instruction", "license": "mit", "weight": 3},
    {"dataset": "LDJnr/Capybara", "field": None, "lang": "en", "category": "reasoning", "license": "apache-2.0", "weight": 2},
    {"dataset": "openai/gsm8k", "field": "question", "lang": "en", "category": "reasoning", "license": "mit", "weight": 1},
    {"dataset": "openai/openai_humaneval", "field": "prompt", "lang": "en", "category": "code", "license": "mit", "weight": 1},
    {"dataset": "CausalLM/GPT-4-Self-Instruct-Japanese", "field": "instruction", "lang": "ja", "category": "instruction", "license": "cc-by-4.0", "weight": 2},
    {"dataset": "llm-jp/oasst1-21k-ja", "field": None, "lang": "ja", "category": "instruction", "license": "apache-2.0", "weight": 3},
)


def http_json(url: str, timeout: int = 60, attempts: int = 5) -> dict:
    import time

    last: Exception | None = None
    for attempt in range(attempts):
        request = urllib.request.Request(url, headers={"User-Agent": "uzu-mtp-prompts"})
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                payload = json.loads(response.read())
            time.sleep(PAGE_DELAY_S)
            return payload
        except Exception as error:  # noqa: BLE001 - retry any transport/parse failure
            last = error
            # The datasets server rate-limits aggressively; back off in minutes.
            time.sleep(min(60, 5 * (4 ** attempt)))
    raise RuntimeError(f"{url}: {last}")


def split_of(dataset: str) -> tuple[str, str]:
    data = http_json(f"{SPLITS_API}?dataset={urllib.parse.quote(dataset)}")
    splits = data.get("splits") or []
    if not splits:
        raise ValueError(f"no splits for {dataset}")
    train = next((entry for entry in splits if entry["split"] == "train"), splits[0])
    return train["config"], train["split"]


FIELD_CANDIDATES = ("instruction", "prompt", "question", "text", "input")


def first_user_turn(row: dict) -> str | None:
    """Capybara / Puffin store the dialogue as a Python-literal string."""
    import ast

    for name in ("conversation", "conversations", "messages"):
        value = row.get(name)
        if value is None:
            continue
        if isinstance(value, str):
            try:
                value = ast.literal_eval(value)
            except (ValueError, SyntaxError):
                continue
        if isinstance(value, list):
            for turn in value:
                if not isinstance(turn, dict):
                    continue
                if turn.get("from") in ("human", "user") or turn.get("role") == "user":
                    text = turn.get("value") or turn.get("content")
                    if isinstance(text, str) and text.strip():
                        return text
                # Capybara stores {"input": ..., "output": ...} pairs.
                text = turn.get("input")
                if isinstance(text, str) and text.strip():
                    return text
    return None


def pick_field(row: dict, field: str | None) -> str | None:
    for name in ([field] if field else []) + list(FIELD_CANDIDATES):
        value = row.get(name)
        if isinstance(value, str) and value.strip():
            return value
    return None


def fetch_prompts(dataset: str, field: str | None, limit: int) -> list[str]:
    config, split = split_of(dataset)
    prompts: list[str] = []
    offset = 0
    page = 100
    while len(prompts) < limit and offset < limit * 5:
        query = urllib.parse.urlencode(
            {"dataset": dataset, "config": config, "split": split, "offset": offset, "length": page}
        )
        try:
            payload = http_json(f"{ROWS_API}?{query}")
        except Exception as error:
            print(f"  fetch stopped at offset {offset}: {error}")
            break
        rows = payload.get("rows") or []
        if not rows:
            break
        for entry in rows:
            row = entry.get("row", {})
            text = pick_field(row, field) or first_user_turn(row)
            if text is None:
                # Multi-turn sets: take the first user turn.
                conversations = row.get("conversations") or row.get("messages") or []
                for turn in conversations:
                    if turn.get("from") in ("human", "user") or turn.get("role") == "user":
                        text = turn.get("value") or turn.get("content")
                        break
            if isinstance(text, str):
                prompts.append(text)
        offset += page
    return prompts[:limit]


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def key_of(text: str) -> str:
    return hashlib.sha256(normalize(text).lower().encode("utf-8")).hexdigest()


def holdout_keys() -> set[str]:
    keys: set[str] = set()
    for path in sorted((ROOT / "research").glob("eval_prompts_*.jsonl")):
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            keys.add(key_of(json.loads(line)["prompt"]))
    return keys


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--per-source", type=int, default=2000)
    parser.add_argument("--holdout-fraction", type=float, default=0.05)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    blocked = holdout_keys()
    print(f"holdout prompts: {len(blocked)}")

    examples = []
    seen: set[str] = set()
    for source in SOURCES:
        wanted = args.per_source * source["weight"]
        try:
            raw = fetch_prompts(source["dataset"], source["field"], wanted)
        except Exception as error:
            print(f"skip {source['dataset']}: {error}")
            continue
        kept = 0
        for text in raw:
            if not isinstance(text, str):
                continue
            text = normalize(text)
            if not (20 <= len(text) <= 4000):
                continue
            key = key_of(text)
            if key in blocked or key in seen:
                continue
            seen.add(key)
            examples.append(
                {
                    "id": f"{source['category']}-{len(examples):06d}",
                    "lang": source["lang"],
                    "category": source["category"],
                    "prompt": text,
                    "source": source["dataset"],
                    "license": source["license"],
                }
            )
            kept += 1
        print(f"{source['dataset']}: fetched {len(raw)}, kept {kept}")

    if not examples:
        raise SystemExit("no prompts collected")

    random.Random(args.seed).shuffle(examples)
    holdout = max(1, int(len(examples) * args.holdout_fraction))
    splits = {"holdout": examples[:holdout], "train": examples[holdout:]}

    print(f"total {len(examples)} (train {len(splits['train'])}, holdout {len(splits['holdout'])})")
    if args.dry_run:
        return

    args.out.mkdir(parents=True, exist_ok=True)
    for name, rows in splits.items():
        with (args.out / f"{name}.jsonl").open("w", encoding="utf-8") as handle:
            for row in rows:
                handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    manifest = {
        "seed": args.seed,
        "counts": {name: len(rows) for name, rows in splits.items()},
        "sources": [
            {key: source[key] for key in ("dataset", "lang", "category", "license", "weight")}
            | {"field": source["field"]}
            for source in SOURCES
        ],
        "holdout_guard": "research/eval_prompts_{ja,en}.jsonl",
        "note": "prompts only; responses must be generated by the target model",
    }
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
