KIT_DIR_CANDIDATES = (
    Path("kaggleAI/datasets/uzu-quant-kit-public"),
    Path("../kaggleAI/datasets/uzu-quant-kit-public"),
)


def kit_revision(explicit: str | None) -> tuple[str, str]:
    """Return (revision, where it came from).

    The kit is published as a dataset version named after the source commit, so
    a kernel must download that commit rather than whatever is newest.
    """
    if explicit:
        return explicit, "--kit-revision"
    env = os.environ.get("UZU_KIT_REVISION")
    if env:
        return env, "UZU_KIT_REVISION"
    for directory in KIT_DIR_CANDIDATES:
        # hf download --revision takes the dataset commit, not the source repo commit.
        pinned = directory / ".hf_revision"
        if pinned.exists():
            commit = pinned.read_text(encoding="utf-8").strip()
            if commit:
                return commit, str(pinned)
    result = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise SystemExit("cannot determine the kit revision; pass --kit-revision")
    return result.stdout.strip(), "git HEAD (kit may not be published there)"


def slug(kernel_id: str) -> str:
    return kernel_id.split("/")[-1]


# JAX changes numerics between releases, so the kernel pins what the numbers were
# taken with. Override with --jax-version when intentionally moving.
JAX_VERSION = "0.12.0.1"


def build_pip_args(platform: str, jax_version: str) -> str:
    lalamo = "git+https://github.com/trymirai/lalamo@e401e17761f2fcd337b0cf20218d67d656e6ecba"
    jax = f"jax[cuda12]=={jax_version}" if platform == "gpu" else f"jax=={jax_version}"
    return f'"{lalamo}", "{jax}", "huggingface_hub", "tokenizers"'


def render_external(spec: dict, platform: str, kit_repo: str, kit_revision: str, jax_version: str, model_repo: str) -> str:
    corpora = list((spec.get("eval") or {}).get("corpora", {}).values())
    if not corpora:
        raise SystemExit("invalid spec: eval.corpora is required for external-eval")
    args = "\n".join(f"command += ['--corpus', '/kaggle/working/kit/{corpus}']" for corpus in corpora)
    return EXTERNAL_TEMPLATE.format(
        jax_platform=platform,
        pip_args=build_pip_args(platform, jax_version),
        kit_repo=kit_repo,
        kit_revision=kit_revision,
        model_repo=model_repo,
        corpora_args=args,
    )


def render(spec: dict, platform: str, kit_repo: str, kit_revision: str, jax_version: str,
           hf_results: str | None, eval_dtype: str | None = None) -> str:
    extra: list[str] = []
    if eval_dtype:
        extra.append(f"command += ['--eval-dtype', {eval_dtype!r}]")
    if hf_results:
        extra.append(f"command += ['--hf-results', {hf_results!r}]")
    if platform == "cpu":
        extra.append("command += ['--jax-platform', 'cpu']")
    return KERNEL_TEMPLATE.format(
        lane_spec=json.dumps(spec, ensure_ascii=False),
        jax_platform=platform,
        pip_args=build_pip_args(platform, jax_version),
        kit_repo=kit_repo,
        kit_revision=kit_revision,
        extra_args="\n".join(extra),
    )


def dataset_sources(spec: dict) -> list[str]:
    kaggle = spec.get("kaggle", {})
    if not isinstance(kaggle, dict):
        raise SystemExit("invalid spec: kaggle must be an object")
    configured = kaggle.get("dataset_sources", [])
    if configured:
        if not isinstance(configured, list) or not all(isinstance(item, str) for item in configured):
            raise SystemExit("invalid spec: kaggle.dataset_sources must be a list of strings")
        return list(configured)
    source = spec.get("model", {}).get("bf16_source")
    if not source:
        return []
    # /kaggle/input/<slug> -> <owner>/<slug> is not recoverable from the path,
    # so the spec may name it explicitly; otherwise the caller passes it.
    return [source] if "/" in source and source.count("/") == 1 else []


def load_spec(path: Path) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise SystemExit(f"invalid spec: {path}: {error}") from error
    if not isinstance(value, dict) or not value.get("lane"):
        raise SystemExit("invalid spec: top-level object and non-empty lane required")
    return value


def validate_dataset_sources(datasets: list[str]) -> None:
    invalid = [item for item in datasets if item.count("/") != 1 or any(not part for part in item.split("/"))]
    if invalid:
        raise SystemExit(f"invalid dataset id(s): {', '.join(invalid)} (expected owner/dataset)")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", type=Path, required=True)
    parser.add_argument("--kernel-id", required=True, help="owner/slug")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--kind", choices=("lane", "external-eval", "qad"), default="lane")
    parser.add_argument("--student-repo", default=None, help="HF repo holding the QAD student")
    parser.add_argument("--steps", default="50")
    parser.add_argument("--seq", default="32")
    parser.add_argument("--optimizer", default="adamw")
    parser.add_argument("--parallel", default="tensor")
    parser.add_argument("--lr", default="5e-4")
    parser.add_argument("--muon-lr", default="1e-3")
    parser.add_argument("--grad-clip", default="1.0")
    parser.add_argument("--model-repo", default=None, help="HF repo to measure (external-eval)")
    parser.add_argument("--platform", choices=("cpu", "gpu"), default="cpu")
    parser.add_argument("--dataset", action="append", default=[], help="owner/dataset (repeatable)")
    parser.add_argument("--kit-repo", default="yamahei21/uzu-quant-kit")
    parser.add_argument("--jax-version", default=JAX_VERSION)
    parser.add_argument("--kit-revision", default=None,
                        help="kit commit to download (default: this repo's HEAD)")
    parser.add_argument("--hf-results", default=None, help="repo for run_lane --hf-results")
    parser.add_argument("--eval-dtype", choices=("bfloat16", "float32"), default=None,
                        help="forwarded to run_lane; use float32 to compare against older runs")
    parser.add_argument("--push", action="store_true")
    args = parser.parse_args()

    if args.kernel_id.count("/") != 1 or any(not part for part in args.kernel_id.split("/")):
        raise SystemExit("--kernel-id must look like owner/slug")
    spec = load_spec(args.spec)
    datasets = args.dataset or dataset_sources(spec)
    if not datasets:
        raise SystemExit(
            "no dataset source: pass --dataset owner/dataset (the spec's bf16_source is a mount path)"
        )
    validate_dataset_sources(datasets)

    revision, revision_source = kit_revision(args.kit_revision)
    print(f"kit revision: {revision} ({revision_source})")
    if args.kind == "qad" and not args.student_repo:
        raise SystemExit("--student-repo is required for --kind qad")
    if args.kind == "qad":
        args.platform = "gpu"
    if args.kind == "external-eval" and not args.model_repo:
        raise SystemExit("--model-repo is required for --kind external-eval")

    args.out.mkdir(parents=True, exist_ok=True)
    name = slug(args.kernel_id)
    if args.kind == "qad":
        code = QAD_TEMPLATE.format(
            pip_args=build_pip_args("gpu", args.jax_version),
            kit_repo=args.kit_repo, kit_revision=revision,
            student_repo=args.student_repo,
            steps=args.steps, seq=args.seq, optimizer=args.optimizer,
            parallel=args.parallel, lr=args.lr, muon_lr=args.muon_lr,
            grad_clip=args.grad_clip,
        )
    elif args.kind == "external-eval":
        code = render_external(spec, args.platform, args.kit_repo, revision, args.jax_version, args.model_repo)
    else:
        code = render(spec, args.platform, args.kit_repo, revision, args.jax_version, args.hf_results, args.eval_dtype)
    (args.out / f"{name}.py").write_text(code, encoding="utf-8")
    metadata = {
        "id": args.kernel_id,
        "title": name.replace("-", " ")[:50],
        "code_file": f"{name}.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": args.platform == "gpu",
        "enable_tpu": False,
        "enable_internet": True,
        "keywords": ["gpu"] if args.platform == "gpu" else [],
        "dataset_sources": datasets,
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (args.out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.out} (platform={args.platform}, datasets={datasets})")

    if args.push:
        try:
            subprocess.run(["kaggle", "kernels", "push", "-p", str(args.out)], check=True)
        except (OSError, subprocess.CalledProcessError) as error:
            code = getattr(error, "returncode", "spawn")
            raise SystemExit(f"kaggle kernels push failed ({code}): {error}") from error


if __name__ == "__main__":
    main()
