#!/usr/bin/env python3
"""Turn a lane spec into a ready-to-push Kaggle kernel.

Every experiment on a new model used to need a hand-written kernel script
(install, download the kit, locate the BF16 source, call the pipeline). All of
that is mechanical and identical, so it lives here. The lane spec itself stays
the source of truth and is run by `scripts/run_lane.py` inside the kernel.

Usage:
    python scripts/make_kaggle_kernel.py --spec lanes/clean-suite-08b.json \
        --kernel-id yamahei21python/uzu-lane-clean-08b --out /tmp/kernel-clean
    python scripts/make_kaggle_kernel.py --spec ... --out ... --gpu --push

The generated directory contains:
    <slug>.py              the kernel entry point
    lane.json              a copy of the spec (so the kernel is self-contained)
    kernel-metadata.json   ready for `kaggle kernels push`
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path

KERNEL_TEMPLATE = '''"""Auto-generated by scripts/make_kaggle_kernel.py - do not edit by hand."""
import json
import os
import subprocess
import sys
from pathlib import Path

os.environ["JAX_PLATFORM_NAME"] = {jax_platform!r}

subprocess.run([sys.executable, "-m", "pip", "install", "-q",
    {pip_args}], check=True)
subprocess.run(["hf", "download", {kit_repo!r}, "--repo-type", "dataset",
    "--local-dir", "/kaggle/working/kit"], check=True)
subprocess.run([sys.executable, "/kaggle/working/kit/scripts/build_kit.py",
    "--check", "/kaggle/working/kit"], check=True)

spec = json.loads(Path("/kaggle/working/lane.json").read_text())
# The kit is downloaded, not mounted, so rewrite its path for this session.
spec.setdefault("paths", {{}})["kit"] = "kit"
Path("/kaggle/working/lane.json").write_text(json.dumps(spec, indent=2))

command = [sys.executable, "/kaggle/working/kit/scripts/run_lane.py",
           "--spec", "/kaggle/working/lane.json"]
{extra_args}
subprocess.run(command, check=True)
'''


def slug(kernel_id: str) -> str:
    return kernel_id.split("/")[-1]


def build_pip_args(platform: str) -> str:
    lalamo = "git+https://github.com/trymirai/lalamo@e401e17761f2fcd337b0cf20218d67d656e6ecba"
    jax = "jax[cuda12]" if platform == "gpu" else "jax"
    return f'"{lalamo}", "{jax}", "huggingface_hub", "tokenizers"'


def render(spec: dict, kernel_id: str, platform: str, kit_repo: str, hf_results: str | None) -> str:
    extra: list[str] = []
    if hf_results:
        extra.append(f"command += ['--hf-results', {hf_results!r}]")
    if platform == "cpu":
        extra.append("command += ['--jax-platform', 'cpu']")
    return KERNEL_TEMPLATE.format(
        jax_platform=platform,
        pip_args=build_pip_args(platform),
        kit_repo=kit_repo,
        extra_args="\n".join(extra),
    )


def dataset_sources(spec: dict) -> list[str]:
    source = spec.get("model", {}).get("bf16_source")
    if not source:
        return []
    # /kaggle/input/<slug> -> <owner>/<slug> is not recoverable from the path,
    # so the spec may name it explicitly; otherwise the caller passes it.
    return [source] if "/" in source and source.count("/") == 1 else []


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--spec", type=Path, required=True)
    parser.add_argument("--kernel-id", required=True, help="owner/slug")
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--platform", choices=("cpu", "gpu"), default="cpu")
    parser.add_argument("--dataset", action="append", default=[], help="owner/dataset (repeatable)")
    parser.add_argument("--kit-repo", default="yamahei21/uzu-quant-kit")
    parser.add_argument("--hf-results", default=None, help="repo for run_lane --hf-results")
    parser.add_argument("--push", action="store_true")
    args = parser.parse_args()

    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    datasets = args.dataset or dataset_sources(spec)
    if not datasets:
        raise SystemExit(
            "no dataset source: pass --dataset owner/dataset (the spec's bf16_source is a mount path)"
        )

    args.out.mkdir(parents=True, exist_ok=True)
    name = slug(args.kernel_id)
    (args.out / f"{name}.py").write_text(
        render(spec, args.kernel_id, args.platform, args.kit_repo, args.hf_results),
        encoding="utf-8",
    )
    shutil.copy2(args.spec, args.out / "lane.json")
    metadata = {
        "id": args.kernel_id,
        "title": name.replace("-", " ")[:50],
        "code_file": f"{name}.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": args.platform == "gpu",
        "enable_tpu": False,
        "enable_internet": True,
        "keywords": ["gpu"] if args.platform == "gpu" else [],
        "dataset_sources": datasets,
        "kernel_sources": [],
        "competition_sources": [],
        "model_sources": [],
    }
    (args.out / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {args.out} (platform={args.platform}, datasets={datasets})")

    if args.push:
        subprocess.run(["kaggle", "kernels", "push", "-p", str(args.out)], check=True)


if __name__ == "__main__":
    main()
